import json
import os
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

root = Path(__file__).resolve().parents[1]
password = os.environ['VITAL_TEST_PASSWORD']  # password of the isolated test backend
base = os.environ.get("VITAL_TEST_URL", "http://127.0.0.1:8208")
errors = []
with sync_playwright() as p:
    browser = p.chromium.launch(headless=True)
    context = browser.new_context(viewport={"width":390,"height":844},device_scale_factor=1,is_mobile=True,has_touch=True)
    page = context.new_page()
    page.on("pageerror",lambda e:errors.append(str(e)))
    page.goto(base)
    expect(page.locator('#login-form')).to_be_visible()
    print("Login controls:",page.locator('button').all_text_contents())
    page.locator('[data-action="demo"]').click()
    expect(page.locator('h1')).to_have_text('Today')
    page.screenshot(path=str(root/'review/mobile-dashboard.png'),full_page=True)
    for width in (320,390,430,1280):
        page.set_viewport_size({"width":width,"height":900})
        assert page.evaluate('document.documentElement.scrollWidth <= innerWidth'),f'overflow at {width}'
    page.set_viewport_size({"width":1280,"height":900})
    page.screenshot(path=str(root/'review/desktop-dashboard.png'),full_page=True)
    page.locator('[data-action="exit-demo"]').click()
    page.set_viewport_size({"width":390,"height":844})
    page.locator('#login-form [name=password]').fill(password)
    page.locator('#login-form button[type=submit]').click()
    expect(page.locator('h1')).to_have_text('Today')
    page.locator('.avatar').click()
    page.locator('#profile-form [name=name]').fill('Test')
    page.locator('#profile-form [name=birthdate]').fill('1986-11-10')
    page.locator('#profile-form button[type=submit]').click()
    expect(page.locator('.welcome')).to_contain_text('Test')
    page.locator('.bottom-nav [data-action="nav:nutrition"]').click()
    page.locator('[data-action="add:meal"]').first.click()
    page.locator('dialog [name=name]').fill('Test lunch')
    page.locator('dialog [name=calories]').fill('600')
    page.locator('dialog [name=protein]').fill('40')
    page.locator('dialog [name=carbs]').fill('70')
    page.locator('dialog [name=fat]').fill('18')
    page.locator('dialog button[type=submit]').click()
    expect(page.locator('.entry-text').filter(has_text='Test lunch').first).to_be_visible()
    page.locator('[data-action="water:250"]').click()
    expect(page.locator('.water-visual strong')).to_contain_text('l')
    page.locator('.bottom-nav [data-action="nav:health"]').click()
    page.locator('[data-action="add:vitals"]').click()
    page.locator('dialog [name=hrv]').fill('55')
    page.locator('dialog [name=rhr]').fill('58')
    page.locator('dialog button[type=submit]').click()
    expect(page.locator('dialog')).not_to_be_visible()
    page.locator('[data-action="tab:sleep"]').click()
    page.locator('[data-action="add:sleep"]').first.click()
    page.locator('dialog [name=sleep_hours]').fill('8')
    page.locator('dialog [name=bed_hours]').fill('8.5')
    page.locator('dialog button[type=submit]').click()
    expect(page.locator('.sleep-hero')).to_contain_text('h')
    page.locator('[data-action="tab:age"]').click()
    expect(page.locator('.wearable-age')).to_be_visible()
    page.locator('.optional-labs>summary').click()
    page.locator('[data-action="add:lab"]').click()
    values=dict(albumin=45,creatinine=80,glucose=5,crp=1,lymphocytes=30,mcv=90,rdw=13,alp=65,wbc=6)
    for key,value in values.items():page.locator(f'dialog [name={key}]').fill(str(value))
    page.locator('dialog button[type=submit]').click()
    expect(page.locator('.biological-card .age-result>strong')).to_be_visible()
    expect(page.locator('.biological-card .age-result>strong')).to_contain_text('32.')  # waits for the re-render
    page.screenshot(path=str(root/'review/mobile-biological-age.png'),full_page=True)
    page.locator('[data-action="tab:journal"]').click()
    page.locator('[data-action="add:journal"]').first.click()
    page.locator('dialog [name=notes]').fill('Test journal entry')
    page.locator('dialog button[type=submit]').click()
    expect(page.locator('.journal-note').first).to_contain_text('Test journal entry')
    page.locator('.bottom-nav [data-action="nav:workouts"]').click()
    page.locator('[data-action="template:fullbody"]').click()
    expect(page.locator('.set-row')).to_have_count(7)
    page.locator('dialog button[type=submit]').click()
    expect(page.locator('.plan-row').first).to_contain_text('Full body')
    page.locator('[data-action^="start-plan:"]').first.click()
    page.locator('dialog [name=rpe]').fill('6')
    page.locator('dialog [name=set_done]').first.check()
    page.locator('dialog button[type=submit]').click()
    expect(page.locator('.entry-text').filter(has_text='Full body').first).to_be_visible()
    page.locator('.bottom-nav [data-action="nav:coach"]').click()
    expect(page.locator('.notice')).to_contain_text('OpenRouter')
    page.locator('#chat-message').fill('How am I doing?')
    page.locator('#chat-form button[type=submit]').click()
    expect(page.locator('#toast')).to_contain_text('OpenRouter API key')
    page.locator('.avatar').click()
    expect(page.locator('#profile-form')).to_be_visible()
    page.locator('#profile-form [name=offline_cache]').check(force=True)
    with page.expect_response(lambda r:r.url.endswith('/api/profile')) as updated:
        page.locator('#profile-form button[type=submit]').click()
    assert updated.value.request.post_data_json['offline_cache'] is True
    page.wait_for_function("() => localStorage.getItem('vital-snapshot') !== null")
    page.wait_for_timeout(500)
    page.reload()
    expect(page.locator('h1')).to_have_text('Settings')
    page.wait_for_function("() => localStorage.getItem('vital-snapshot') !== null")
    page.wait_for_function("() => navigator.serviceWorker.controller !== null",timeout=15000)
    context.set_offline(True)
    page.reload()
    expect(page.locator('.offline-banner')).to_be_visible()
    context.set_offline(False)
    page.reload()
    expect(page.locator('h1')).to_have_text('Settings')
    page.locator('[data-action="logout"]').click()
    expect(page.locator('#login-form')).to_be_visible()
    assert not page.evaluate("localStorage.getItem('vital-snapshot')")
    assert not errors,errors
    print(json.dumps({"status":"passed","browser_errors":errors,"viewports":[320,390,430,1280],"flows":["login","profile","meal","water","vitals","sleep","phenoage","journal","plans","workout","AI without key","offline","logout"]}))
    browser.close()
